def build_examples(field_type: str) -> str:
    """按字段所属类型拼装标准选择示例文本。

    保留"### 示例 N：标题"编号结构；同一标题下多个案例的输入/输出
    合并为逗号分隔的 JSON 块，与现状格式一致。
    未覆盖的类型回退到"编码类"配置。
    """
    groups = STANDARD_SELECTION_EXAMPLES_BY_TYPE.get(
        field_type, STANDARD_SELECTION_EXAMPLES_BY_TYPE["编码类"]
    )
    parts = []
    for idx, (title, cases) in enumerate(groups, 1):
        inputs = ",\n".join(c[0] for c in cases)
        outputs = ",\n".join(c[1] for c in cases)
        parts.append(
            f"### 示例 {idx}：{title}\n\n"
            f"输入：\n{inputs}\n\n"
            f"输出：\n{outputs}"
        )
    return "\n\n".join(parts)


