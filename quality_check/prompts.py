# 业务含义检查 Prompt
# ============================================================

BUSINESS_MEANING_SYSTEM = """你的任务是检查数据字段的"业务含义"描述是否有效。

## 输入数据结构

每行数据包含以下字段：
- row_index: 行号（输出时必须与此对应）
- 字段中文名: 待检查字段的中文名称
- 业务含义: 字段的业务含义描述

## 输出字段结构

每行输出包含以下字段：
- row_index: 行号，与输入对应
- is_meaningful: 布尔值，业务含义是否有效（true=有效，false=无效）
- reason: 判断过程和原因说明，需详细描述比较分析的过程

## 判断标准

首先判断字段中文名是否有效。

### 判定为**有效**的情况：
1. **见名知意**：字段中文名本身足够清晰，业务含义无论怎样写都视为有效
   - 例：字段中文名="客户名称"，业务含义="客户名称" -> 有效
   - 例：字段中文名="开户日期"，业务含义="开户的日期" -> 有效
2. **有实质描述**：业务含义提供了字段中文名中没有的信息，比如业务背景、用途说明或具体描述
   - 例：字段中文名="客户状态"，业务含义="标识客户在系统中的当前状态，包括正常、冻结、注销等" -> 有效
   - 例：字段中文名="交易金额"，业务含义="记录一笔交易的实际发生金额，单位为元" -> 有效

### 判定为**无效**的情况：
1. **完全复制**：业务含义与字段中文名完全相同或几乎相同
   - 例：字段中文名="第二结论类型"，业务含义="第二结论类型" -> 第二结论不是常见金融名称，不属于见名知意，且业务含义未进行解释，无效
2. **简单加词**：业务含义只是在字段中文名基础上添加"的"、"是"、"字段"等无实质意义的词语
   - 例：字段中文名="CDA规则结果"，业务含义="CDA的规则结果" -> 无效
   - 例：字段中文名="CDA规则结果"，业务含义="CDA规则结果字段" -> 无效
3. **语义重复**：业务含义与字段中文名在语义上完全等价，只是换了说法
   - 例：字段中文名="转案欺诈类型"，业务含义="指转案欺诈的不同类别" -> 无效

## 判断要求
- 仔细比较字段中文名和业务含义的语义差异
- 对于模糊的情况，倾向于判定为有效
- 在reason字段中，请详细说明你的判断过程，包括你如何比较两者、为什么认为有效或无效
- reason字段请用中文描述

## 示例

输入：
[
  {"row_index": 0, "字段中文名": "客户名称", "业务含义": "客户名称"},
  {"row_index": 1, "字段中文名": "CDA规则结果", "业务含义": "CDA规则结果字段"}
]

输出：
[
  {
    "row_index": 0,
    "is_meaningful": true,
    "reason": "字段中文名'客户名称'属于见名知意，业务含义即使与字段名相同也视为有效。"
  },
  {
    "row_index": 1,
    "is_meaningful": false,
    "reason": "字段中文名'CDA规则结果'不属于见名知意的常见金融名称，业务含义'CDA规则结果字段'只是在原名称基础上添加'字段'二字，未提供实质信息，无效。"
  }
]"""

BUSINESS_MEANING_USER = """请对以下每一行数据判断"业务含义"是否有效。

数据（JSON数组）：
{data}

请对每一行返回判断结果，确保row_index与输入数据对应。"""


