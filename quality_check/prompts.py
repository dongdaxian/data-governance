ENUM_NORMALIZATION_SYSTEM = """你的任务是将枚举值规范化为标准格式。

## 输入数据结构

每行数据包含以下字段：
- row_index: 行号（输出时必须与此对应）
- 枚举值: 原始枚举值字符串

## 输出字段结构

每行输出包含以下字段：
- row_index: 行号，与输入对应
- normalized: 规范化后的枚举值，格式为"代码-码值;代码-码值"
- needs_normalization: 布尔值，是否需要规范化（原始格式已是标准格式则为false）

## 标准格式要求

- 每个枚举项格式为"代码-码值"，代码与码值之间用英文连字符"-"连接
- 多个枚举项之间用英文分号";"分隔
- 代码只能是数字和字母的组合（如1、01、A、B、A01、B02等），保留原始代码原样：不补前导零，也不去掉已有的前导零
- 如果原始数据没有代码，从01开始按顺序编号
- 不要改变码值本身的文字内容

## 标准格式示例
- 1-成功;2-失败;3-处理中（原始代码为1、2、3时）
- 01-成功;02-失败;03-处理中（原始代码本身是01、02、03时）
- A-男;B-女
- 1-现金;2-银行卡;3-支票
- A01-现金;B02-银行卡;C03-支票（字母与数字组合代码，原样保留）

## 常见不规范格式及处理方式

| 原始格式 | 规范化后 | 说明 |
|---|---|---|
| 01-成功,02-失败 | 01-成功;02-失败 | 逗号改分号，代码原样保留 |
| 1.现金 2.银行卡 3.支票 4.汇款 | 1-现金;2-银行卡;3-支票;4-汇款 | 点号改连字符，代码原样保留（不补零） |
| 成功,失败,处理中 | 01-成功;02-失败;03-处理中 | 无代码，从01编号 |
| (1)成功 (2)失败 | 1-成功;2-失败 | 去除括号，代码原样保留 |
| 01：成功 02：失败 | 01-成功;02-失败 | 中文冒号改连字符，代码原样保留 |
| 01=成功\\|02=失败 | 01-成功;02-失败 | 等号改连字符，竖线改分号，代码原样保留 |
| 男/女 | 01-男;02-女 | 斜杠改分号，无代码从01编号 |
| 账户冻结-银行发起-CLOP;可关闭状态-CLOR | CLOP-账户冻结-银行发起;CLOR-可关闭状态 | 代码和码值顺序反了，调整格式 |
| 1-男;female-女 | 1-男;female-女 | 满足代码只能是数字和字母的组合限制条件，无需修改 |
| 成功,有-失败 | 01-成功;02-失败 | 第一组代码缺失，第二组代码包含中文，重新编号 |

## 处理要求
- 如果原始数据已经是标准格式（代码-码值;代码-码值），原样返回并设置needs_normalization为false
- 如果原始数据需要任何调整，设置needs_normalization为true并返回规范化后的结果
- 保留原始码值的文字内容，不要修改码值本身
- 如果枚举值为空字符串，原样返回空字符串并设置needs_normalization为false

## 示例

输入：
[
  {"row_index": 0, "枚举值": "1.现金 2.银行卡 3.支票"},
  {"row_index": 1, "枚举值": "01-成功;02-失败"}
]

输出：
[
  {
    "row_index": 0,
    "normalized": "1-现金;2-银行卡;3-支票",
    "needs_normalization": true
  },
  {
    "row_index": 1,
    "normalized": "01-成功;02-失败",
    "needs_normalization": false
  }
]"""

ENUM_NORMALIZATION_USER = """请对以下每一行数据的"枚举值"进行规范化处理。

数据（JSON数组）：
{data}

请对每一行返回规范化结果，确保row_index与输入数据对应。"""
