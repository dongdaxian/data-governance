NAME_NORMALIZE_SYSTEM = """你的任务是对待新增字典的字段中文名进行规范化。

## 输入数据结构

每行数据包含以下字段：
- row_index: 行号（输出时必须与此对应）
- field_name: 待规范化的中文字段名
- business_meaning: 业务定义

## 规范化要求

1. 判断字段名是否规范：规范名应简洁、语义明确、符合数据标准命名习惯（通常是一个名词性短语，如"权限编号""开卡日期"）。
2. 以下情况视为"非常不规范"，需要用大模型改写为规范中文名：
   - 含序号尾巴：如"属性值5"、"名称KEY1"
   - 含英文残留、缩写堆砌、无意义的符号或填充词
3. 改写后的名称必须：
   - 保留原字段的核心业务语义，去掉仅用于标识的杂质（码值 KEY、序号等）
   - 简短，符合数据标准命名习惯（通常 2-8 个字，形如"权限编号"）
4. 若原字段名已规范（简洁、语义明确），原样返回，changed=false。
5. changed 必须如实标记：发生了改写为 true，原样保留为 false。
6. reasoning 用中文简要说明判断与改写依据。

## 规范化示例

输入：
{"row_index": 0, "field_name": "数据权限代码KEY值5", "field_type": "编码类", "enum_values": "", "business_meaning": "角色数据权限维护功能维护的数据权限代码KEY值5（共5个属性）"}

输出：
{"row_index": 0, "normalized_name": "权限编号", "changed": true, "reasoning": "原名称'数据权限代码KEY值5'含编码杂质'KEY值5'，去掉后核心语义为'数据权限代码'，进一步简化为规范名'权限编号'。"}

## 输出字段结构

每行输出包含以下字段：
- row_index: 行号，与输入对应
- normalized_name: 规范化后的中文字段名
- changed: 是否发生了改写（true/false）
- reasoning: 判断与改写依据（中文，简述）"""


