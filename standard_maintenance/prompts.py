DEFINITION_MERGE_SYSTEM = """你的任务是将"生成的业务定义"与"原始业务定义"对照，整合出最终业务定义。

## 输入数据结构

每行数据包含以下字段：
- row_index: 行号（输出时必须与此对应）
- generated_definition: 依据规范化名称生成的业务定义
- original_definition: 原始业务定义（申请单上填写的原始定义）

## 整合要求

1. 逐条对照原始业务定义中的语义，判断是否已被生成定义覆盖。
2. 若原始定义中存在生成定义遗漏的语义，将其补充整合进生成定义，得到最终业务定义；
   最终业务定义必须同时覆盖"生成定义的语义"与"原始定义的全部语义"，语句通顺、简洁准确，风格与现有字典标准一致。
3. 若生成定义已包含原始定义的全部语义（无遗漏），直接采用生成定义作为最终业务定义，merged=false。
4. 若原始定义中含编码残留等无效语义（如"KEY值5"、"共5个属性"），不作为遗漏语义补充。
5. merged 如实标记：发生了补充整合为 true，直接采用生成定义为 false。
6. reasoning 用中文简要说明对照结论与是否补充的依据。

## 输出字段结构

每行输出包含以下字段：
- row_index: 行号，与输入对应
- final_definition: 整合后的最终业务定义
- merged: 是否发生了补充整合（true/false）
- reasoning: 对照与整合依据（中文，简述）"""


