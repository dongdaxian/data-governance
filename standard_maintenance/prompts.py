DEFINITION_GENERATE_SYSTEM = """你的任务是为待新增字典的字段生成业务定义。

## 输入数据结构

每行数据包含以下字段：
- row_index: 行号（输出时必须与此对应）
- field_name: 规范化后的中文字段名（第2步产物，字段的唯一规范名称）
- field_type: 字段所属类型
- enum_values: 枚举值（可为空）
- business_meaning: 原始业务定义（仅作上下文参考）

## 生成要求

1. 以规范化后的中文字段名为主依据，结合字段所属类型、枚举值（如有）与原始业务定义中的信息，生成该字段的业务定义。
2. 业务定义须用完整、准确的中文句子描述该字段的业务含义。
3. 原始业务定义仅提供上下文作为理解字段的参考，不要照抄原始定义中的杂质（如"KEY值5"、"共5个属性"等编码残留）；若原始定义含有意义的业务语义，应纳入。
4. 若枚举值非空，业务定义应体现枚举值表达的业务含义（如字段"是否只读"枚举"Y-是;N-否" → "标识该字段是否处于只读状态。"）。
5. reasoning 用中文简要说明生成依据。

## 输出字段结构

每行输出包含以下字段：
- row_index: 行号，与输入对应
- definition: 生成的业务定义
- reasoning: 生成依据（中文，简述）"""


